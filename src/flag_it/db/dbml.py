"""Write docs/schema.dbml from a migrated database, so the diagram always matches the tables.

    python -m flag_it.db.dbml                 # rewrite docs/schema.dbml (FLAG_IT_DATABASE_URL)
    python -m flag_it.db.dbml --check         # exit 1 if docs/schema.dbml is out of date
    python -m flag_it.db.dbml --url URL       # read another database, e.g. the test database
"""

import argparse
import sys
from pathlib import Path
from typing import Any

from flag_it.db.connection import Conn, connect

DBML_PATH = Path(__file__).resolve().parents[3] / "docs" / "schema.dbml"

HEADER = """\
// Flag-It database schema. GENERATED by `python -m flag_it.db.dbml` from the migrations. Do not edit.
// To change a table, add a migration in src/flag_it/db/migrations/versions/, then regenerate.
// Field meanings: docs/contracts.md. View as a diagram: paste into https://dbdiagram.io.
//
// Conventions
// - Keys are UUIDs generated in Python, so any machine can create rows.
// - Money is numeric(12,2). Scores are double precision, so Python floats read back exactly.
// - Every table is append-only: triggers reject UPDATE, DELETE, and TRUNCATE. The one exception is
//   decision_run, whose route, decided_by, and escalation_reasons are filled in once, when the agent finishes.
// - Check constraints are listed as comments inside each table.

Project flag_it {
  database_type: 'PostgreSQL'
}
"""

_TABLES = """
SELECT c.relname::text AS name, obj_description(c.oid, 'pg_class') AS note
FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
WHERE n.nspname = 'public' AND c.relkind = 'r' AND c.relname <> 'alembic_version'
ORDER BY c.oid
"""

_COLUMNS = """
SELECT a.attname::text AS name, format_type(a.atttypid, a.atttypmod) AS type, a.attnotnull AS not_null,
       pg_get_expr(d.adbin, d.adrelid) AS default_expr, col_description(a.attrelid, a.attnum) AS note
FROM pg_attribute a
LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
WHERE a.attrelid = %s::regclass AND a.attnum > 0 AND NOT a.attisdropped
ORDER BY a.attnum
"""

_CONSTRAINTS = """
SELECT con.conname::text AS name, con.contype::text AS kind, pg_get_constraintdef(con.oid) AS definition,
       ARRAY(SELECT a.attname::text FROM unnest(con.conkey) WITH ORDINALITY AS k(num, pos)
             JOIN pg_attribute a ON a.attrelid = con.conrelid AND a.attnum = k.num ORDER BY k.pos) AS columns,
       con.confrelid::regclass::text AS ref_table,
       ARRAY(SELECT a.attname::text FROM unnest(con.confkey) WITH ORDINALITY AS k(num, pos)
             JOIN pg_attribute a ON a.attrelid = con.confrelid AND a.attnum = k.num ORDER BY k.pos) AS ref_columns
FROM pg_constraint con
WHERE con.conrelid = %s::regclass
ORDER BY con.conname
"""

_INDEXES = """
SELECT i.relname::text AS name, ix.indisunique AS is_unique, pg_get_expr(ix.indpred, ix.indrelid) AS predicate,
       ARRAY(SELECT pg_get_indexdef(ix.indexrelid, k, true) FROM generate_series(1, ix.indnkeyatts) AS k
             ORDER BY k) AS columns
FROM pg_index ix JOIN pg_class i ON i.oid = ix.indexrelid
WHERE ix.indrelid = %s::regclass
  AND NOT EXISTS (
      SELECT 1 FROM pg_constraint c WHERE c.conindid = ix.indexrelid AND c.contype IN ('p', 'u', 'x')
  )
ORDER BY i.relname
"""


def _text(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def _type(name: str) -> str:
    return f'"{name}"' if " " in name or "[" in name else name


def _oneline(sql_text: str) -> str:
    """Postgres prints some definitions over several lines; a // comment must stay on one."""
    return " ".join(sql_text.split())


def _cols(columns: list[str]) -> str:
    return columns[0] if len(columns) == 1 else "(" + ", ".join(columns) + ")"


def _table(conn: Conn, table: dict[str, Any]) -> tuple[list[str], list[str]]:
    """The lines of one Table block, and the Ref lines for its foreign keys."""
    name = table["name"]
    constraints = conn.execute(_CONSTRAINTS, (name,)).fetchall()
    pk = next((c for c in constraints if c["kind"] == "p"), None)
    single_pk = pk["columns"][0] if pk and len(pk["columns"]) == 1 else None

    lines = [f"Table {name} {{"]
    for col in conn.execute(_COLUMNS, (name,)).fetchall():
        settings = []
        if col["name"] == single_pk:
            settings.append("pk")
        elif col["not_null"]:
            settings.append("not null")
        if col["default_expr"] is not None:
            settings.append(f"default: `{col['default_expr']}`")
        if col["note"]:
            settings.append(f"note: {_text(col['note'])}")
        suffix = f" [{', '.join(settings)}]" if settings else ""
        lines.append(f"  {col['name']} {_type(col['type'])}{suffix}")

    index_lines = []
    if pk and single_pk is None:
        index_lines.append(f"    {_cols(pk['columns'])} [pk]")
    for con in constraints:
        if con["kind"] == "u":
            index_lines.append(f"    {_cols(con['columns'])} [unique, name: {_text(con['name'])}]")
    for ix in conn.execute(_INDEXES, (name,)).fetchall():
        settings = (["unique"] if ix["is_unique"] else []) + [f"name: {_text(ix['name'])}"]
        if ix["predicate"]:
            settings.append(f"note: {_text('where ' + _oneline(ix['predicate']))}")
        index_lines.append(f"    {_cols(ix['columns'])} [{', '.join(settings)}]")
    if index_lines:
        lines += ["", "  indexes {", *index_lines, "  }"]

    checks = [con for con in constraints if con["kind"] == "c"]
    if checks:
        lines.append("")
        lines += [f"  // {con['name']}: {_oneline(con['definition'])}" for con in checks]
    if table["note"]:
        lines += ["", f"  Note: {_text(table['note'])}"]
    lines.append("}")

    refs = [
        f"Ref {con['name']}: {name}.{_cols(con['columns'])} > {con['ref_table']}.{_cols(con['ref_columns'])}"
        for con in constraints
        if con["kind"] == "f"
    ]
    return lines, refs


def render(conn: Conn) -> str:
    blocks, refs = [], []
    for table in conn.execute(_TABLES).fetchall():
        lines, table_refs = _table(conn, table)
        blocks.append("\n".join(lines))
        refs += table_refs
    return HEADER + "\n" + "\n\n".join(blocks) + "\n\n" + "\n".join(refs) + "\n"


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(prog="python -m flag_it.db.dbml")
    parser.add_argument("--check", action="store_true", help="exit 1 if docs/schema.dbml is out of date")
    parser.add_argument("--url", help="database URL (default: FLAG_IT_DATABASE_URL)")
    args = parser.parse_args(argv)
    with connect(args.url) as conn:
        text = render(conn)
    if args.check:
        if DBML_PATH.read_text() != text:
            sys.exit(f"{DBML_PATH} is out of date. Run: python -m flag_it.db.dbml")
        return
    DBML_PATH.write_text(text)


if __name__ == "__main__":
    main()
