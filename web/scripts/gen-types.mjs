// Generate src/api/types.ts from the contract's JSON Schemas (src/flag_it/contracts/schema/).
//
//   npm run types          regenerate after the contract changes
//   npm run types:check    fail when the committed file is stale (run it before committing, like the fixtures check)
//
// All schemas are merged into one, so a model nested in several (DecisionRun, Flag) is declared once.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { compile } from "json-schema-to-typescript";

const SCHEMA_DIR = new URL("../../src/flag_it/contracts/schema/", import.meta.url);
const OUT = new URL("../src/api/types.ts", import.meta.url);

// Pydantic gives every property a title, which the compiler would turn into a named type
// (Amount1, TxnId4, ...). Only models keep their titles, so only models get names.
// A key inside "properties" is a field name, so a field called "title" (CitedRule.title) is kept.
function untitled(node, keep = false) {
  if (Array.isArray(node)) return node.map((n) => untitled(n));
  if (node === null || typeof node !== "object") return node;
  return Object.fromEntries(
    Object.entries(node)
      .filter(([key]) => keep || key !== "title")
      .map(([key, value]) => [key, key === "properties" ? fields(value) : untitled(value)]),
  );
}
const fields = (properties) =>
  Object.fromEntries(Object.entries(properties).map(([name, schema]) => [name, untitled(schema)]));

const defs = {};
function add(name, rawSchema) {
  const schema = untitled(rawSchema, true);
  const known = defs[name];
  if (known && JSON.stringify(known) !== JSON.stringify(schema)) {
    throw new Error(`${name} has two different shapes in the schemas; the merged types would be wrong`);
  }
  defs[name] = schema;
}

const models = readdirSync(SCHEMA_DIR).filter((f) => f.endsWith(".json") && f !== "manifest.json").sort();
for (const file of models) {
  const { $defs = {}, ...schema } = JSON.parse(readFileSync(new URL(file, SCHEMA_DIR), "utf8"));
  for (const [name, def] of Object.entries($defs)) add(name, def);
  add(file.replace(/\.json$/, ""), schema);
}
const names = models.map((f) => f.replace(/\.json$/, ""));
const root = {
  title: "Contracts",
  type: "object",
  properties: Object.fromEntries(names.map((n) => [n, { $ref: `#/$defs/${n}` }])),
  additionalProperties: false,
  $defs: defs,
};
const banner = "// Generated by web/scripts/gen-types.mjs from src/flag_it/contracts/schema/. Do not edit.\n";
const text = banner + (await compile(root, "Contracts", { bannerComment: "", additionalProperties: false, format: true }));

if (process.argv.includes("--check")) {
  let committed = "";
  try {
    committed = readFileSync(OUT, "utf8");
  } catch {
    // missing counts as stale
  }
  if (committed !== text) {
    console.error("web/src/api/types.ts is stale: run `npm run types` in web/ and commit it");
    process.exit(1);
  }
  console.log("types are current");
} else {
  writeFileSync(OUT, text);
  console.log(`wrote src/api/types.ts from ${names.length} schemas`);
}
